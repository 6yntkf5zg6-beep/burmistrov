#!/bin/sh
#
# Запуск nginx в «СТАН».
#
# Почему не штатная команда образа: официальный nginx подставляет шаблоны из
# /etc/nginx/templates только если команда контейнера начинается со слова nginx.
# Нам нужен ещё и цикл перезагрузки под обновление сертификата, то есть команда
# другая — значит, подстановку делаем сами.
#
# Скрипт лежит отдельным файлом, а не строкой в docker-compose.yml, намеренно:
# в compose знак доллара приходится экранировать, и ошибка в экранировании
# проявляется не при запуске, а позже — неверным конфигом.
set -e

# Список '$DOMAIN' ограничивает замену одной переменной. Без него envsubst съел бы
# и $host, и $uri, и $remote_addr — nginx остался бы с пустыми переменными.
envsubst '$DOMAIN' \
  < /etc/nginx/templates/default.conf.template \
  > /etc/nginx/conf.d/default.conf

# Проверяем конфиг до старта: лучше упасть здесь с внятной ошибкой, чем молча
# работать со стандартным конфигом, как это было раньше.
nginx -t

# Сертификат обновляется раз в 60 дней, а nginx держит его в памяти с момента
# старта. Раз в сутки перечитываем конфиг, чтобы свежий сертификат попал в работу.
while :; do
  sleep 24h
  nginx -s reload
done &

exec nginx -g 'daemon off;'
